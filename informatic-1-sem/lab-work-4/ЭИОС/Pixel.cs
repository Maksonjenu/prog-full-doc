using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace laba4IMG
{
    /// <summary>
    /// Структура для хранения цвета одного пикселя.
    /// Используем struct, а не class, потому что пикселей могут быть миллионы.
    /// Массив структур Pixel[,] - это ОДИН объект в куче, внутри которого все пиксели
    /// лежат подряд, по 3 байта на пиксель. Если бы Pixel был классом, массив хранил бы
    /// миллионы ссылок (по 8 байт), а каждый пиксель был бы отдельным объектом в куче
    /// (около 24 байт со служебным заголовком) - в разы больше памяти и работы для GC.
    /// </summary>
    public struct Pixel
    {
        // Цветовые компоненты пикселя.
        // Каждая компонента занимает 1 байт (0-255).
        // Порядок компонентов: R (красный), G (зелёный), B (синий).
        // Но для BMP-файлов порядок другой: B, G, R.
        // Почему так? Гуглите (история BMP и совместимость с ранними системами).
        public byte R, G, B;

        // Переопределяем метод ToString для удобного отображения цвета пикселя.
        // Дети мои, всегда переопределяйте ToString в своих структурах и классах.

        // Каждый класс или структура в C# наследуется от базового класса Object,
        // который содержит метод ToString. По умолчанию этот метод возвращает имя типа,
        // но это не очень информативно (в нашем случае будет "laba4IMG.Pixel",
        // laba4IMG - название проекта, Pixel - название структуры).
        // Переопределяя этот метод, мы можем сделать так, чтобы он возвращал 
        // строковое представление цвета пикселя в удобном формате.
        public override string ToString()
        {
            return $"({R}, {G}, {B})";
        }
    }

}
